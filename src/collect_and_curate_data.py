# Blueprint Target Allocations per Language (Total = 1,600 per language)
SUBCATEGORY_QUOTAS = [
    ("FAVOUR", "Clear Favour", 320),
    ("FAVOUR", "Implicit Favour", 128),
    ("FAVOUR", "Sarcastic Favour", 80),
    ("AGAINST", "Clear Against", 192),
    ("AGAINST", "Minimizing Against", 128),
    ("AGAINST", "Sarcastic Against", 160),
    ("NONE", "Off-Topic / Praise", 192),
    ("NONE", "Spam", 128),
    ("NONE", "Unrelated Question", 112),
    ("NONE", "Weather Talk", 96),
    ("NONE", "Neutral Climate Question", 64),
]

def build_language_corpus(lang, seeds_dict):
    corpus = []
    
    for stance, subcat, count in SUBCATEGORY_QUOTAS:
        sub_seeds = seeds_dict[subcat]
        short_seeds = sub_seeds["short"]    # 4 seeds (20%)
        medium_seeds = sub_seeds["medium"]  # 12 seeds (60%)
        long_seeds = sub_seeds["long"]      # 4 seeds (20%)
        
        # Calculate exact count breakdown for this subcategory
        # Enforcing ~20-22% short, ~58-60% medium, ~20% long
        num_short = int(round(count * 0.20))
        num_long = int(round(count * 0.20))
        num_medium = count - num_short - num_long
        
        assigned_seeds = (
            [(s, "Short") for s in random.choices(short_seeds, k=num_short)] +
            [(s, "Medium") for s in random.choices(medium_seeds, k=num_medium)] +
            [(s, "Long") for s in random.choices(long_seeds, k=num_long)]
        )
        
        for base_seed, tier in assigned_seeds:
            noisy_text, noise_tier = apply_social_noise(base_seed, lang, subcat)
            
            corpus.append({
                "text": noisy_text,
                "language": lang,
                "stance": stance,
                "subcategory": subcat,
                "length_tier": tier,
                "noise_level": noise_tier
            })
            
    return corpus

