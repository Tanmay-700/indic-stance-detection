# Modifiers & Variations to simulate genuine noisy YouTube comments
EMOJIS = ["🔥", "🙏", "⚠️", "🌍", "🌱", "💯", "👍", "😡", "🙄", "📢", "👏", "💔", "🤔", ""]
HINDI_PREFIXES = ["भाई सच कहूँ तो ", "बिल्कुल सही बात है! ", "अरे यार, ", "मेरी राय में ", "ध्यान से सुनो, ", ""]
HINDI_SUFFIXES = [" बात बिल्कुल साफ़ है।", " सोचो इस बारे में!", " क्या कहते हो दोस्तों?", " जय हिन्द!", ""]
BENGALI_PREFIXES = ["একদম খাঁটি কথা! ", "ভাই সত্যি বলতে কি, ", "আমার মতে ", "ভালো করে ভেবে দেখুন, ", ""]
BENGALI_SUFFIXES = [" কথাটা মনে রাখবেন।", " আর কিছু বলার নেই!", " আপনি কি একমত?", " ধন্যবাদ।", ""]

def generate_samples(seeds, lang, stance, count=350):
    samples = []
    prefixes = HINDI_PREFIXES if lang == "Hindi" else BENGALI_PREFIXES
    suffixes = HINDI_SUFFIXES if lang == "Hindi" else BENGALI_SUFFIXES

    for i in range(count):
        base = random.choice(seeds)
        p = random.choice(prefixes)
        s = random.choice(suffixes)
        emoji = random.choice(EMOJIS)
        
        # Introduce slight social media variations
        text = f"{p}{base}{s} {emoji}".strip()
        
        # Occasionally mix common typos or repeated punctuation
        if random.random() < 0.3:
            text = text.replace("।", "!!")
        if random.random() < 0.2:
            text = text + " .."
            
        samples.append({
            "text": text,
            "language": lang,
            "stance": stance
        })
    return samples

def build_dataset():
    print("=" * 60)
    print("Generating Stance Detection Benchmark for Indic YouTube Comments")
    print("Claim: 'Climate change and global warming is a serious concern.'")
    print("=" * 60)
    
    all_data = []
    
    # 350 samples each category -> 350 * 3 * 2 = 2,100 samples
    categories = [
        ("Hindi", "Favour", HINDI_FAVOUR_SEEDS, 350),
        ("Hindi", "Against", HINDI_AGAINST_SEEDS, 350),
        ("Hindi", "None", HINDI_NONE_SEEDS, 350),
        ("Bengali", "Favour", BENGALI_FAVOUR_SEEDS, 350),
        ("Bengali", "Against", BENGALI_AGAINST_SEEDS, 350),
        ("Bengali", "None", BENGALI_NONE_SEEDS, 350),
    ]
    
    for lang, stance, seeds, count in categories:
        samples = generate_samples(seeds, lang, stance, count)
        all_data.extend(samples)
        
    df = pd.DataFrame(all_data)
    df = df.sample(frac=1.0, random_state=SEED).reset_index(drop=True)
    df["id"] = [f"{row['language'][:3].upper()}_{i+1:05d}" for i, row in df.iterrows()]
    
    # Reorder columns
    df = df[["id", "text", "language", "stance"]]
    
    # Save full raw dataset
    raw_path = os.path.join(RAW_DIR, "indic_climate_stance_full.csv")
    df.to_csv(raw_path, index=False, encoding="utf-8-sig")
    print(f"Saved full raw corpus ({len(df)} samples) to: {raw_path}")
    
    # Train / Val / Test split (80% / 10% / 10%)
    from sklearn.model_selection import train_test_split
    train_df, temp_df = train_test_split(df, test_size=0.20, random_state=SEED, stratify=df[["language", "stance"]])
    val_df, test_df = train_test_split(temp_df, test_size=0.50, random_state=SEED, stratify=temp_df[["language", "stance"]])
    
    train_path = os.path.join(DATA_DIR, "train.csv")
    val_path = os.path.join(DATA_DIR, "val.csv")
    test_path = os.path.join(DATA_DIR, "test.csv")
    
    train_df.to_csv(train_path, index=False, encoding="utf-8-sig")
    val_df.to_csv(val_path, index=False, encoding="utf-8-sig")
    test_df.to_csv(test_path, index=False, encoding="utf-8-sig")
    
    # Also save an unlabeled test set simulating the instructor's hidden evaluation test set
    hidden_test = test_df[["id", "text", "language"]].copy()
    hidden_path = os.path.join(DATA_DIR, "hidden_test_unlabeled.csv")
    hidden_test.to_csv(hidden_path, index=False, encoding="utf-8-sig")
    
    print("\nDataset Summary:")
    print(f"• Training Set:   {len(train_df)} samples -> {train_path}")
    print(f"• Validation Set: {len(val_df)} samples -> {val_path}")
    print(f"• Test Set:       {len(test_df)} samples -> {test_path}")
    print(f"• Hidden Test:    {len(hidden_test)} samples -> {hidden_path}")
    
    print("\nClass Distribution in Training Set:")
    print(train_df.groupby(["language", "stance"]).size())
    print("=" * 60)

if __name__ == "__main__":
    build_dataset()
