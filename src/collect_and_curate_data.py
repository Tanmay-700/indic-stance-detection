def apply_native_elongation(text, lang):
    """
    Applies very mild native script elongation to at most 1-2 characters.
    Strictly capped to keep dataset natural and fair.
    """
    words = text.split()
    if len(words) < 2:
        return text
    
    # Pick one suitable word to mildly elongate
    idx = random.randint(0, len(words) - 1)
    target = words[idx]
    
    if len(target) < 3:
        return text
        
    if lang == "Hindi":
        # Mildly repeat terminal or penultimate vowel matra / consonant (max 1 extra char)
        if target.endswith("ी"):
            words[idx] = target + "ी"
        elif target.endswith("ा"):
            words[idx] = target + "ा"
        elif target.endswith("े"):
            words[idx] = target + "े"
        elif target.endswith("र") or target.endswith("स") or target.endswith("च"):
            words[idx] = target + target[-1]
    else:
        # Bengali mild repeat
        if target.endswith("ি"):
            words[idx] = target + "ি"
        elif target.endswith("া"):
            words[idx] = target + "া"
        elif target.endswith("ে"):
            words[idx] = target + "ে"
        elif target.endswith("র") or target.endswith("ক") or target.endswith("ম"):
            words[idx] = target + target[-1]
            
    return " ".join(words)

def apply_social_noise(text, lang, subcategory):
    """
    Noise distribution:
    - 30% Clean (Zero noise)
    - 45% Light Noise (Single emoji or natural exclamation)
    - 25% Heavy Noise (Expressive/sarcastic punctuation, emojis, rare <=5% elongation)
    """
    r = random.random()
    
    # 1. 30% CLEAN (Zero emojis, clean punctuation)
    if r < 0.30:
        return text.strip(), "Clean"
        
    # 2. 45% LIGHT NOISE (Single natural emoji or simple punctuation)
    elif r < 0.75:
        if "Favour" in subcategory:
            emoji = random.choice(["🌱", "🙏", "⚠️", "🌍", "!"])
        elif "Against" in subcategory:
            emoji = random.choice(["🙄", "!", "।", ""])
        else:
            emoji = random.choice(["👍", "🙏", "👏", "।", ""])
            
        noise_text = f"{text.rstrip('।!')} {emoji}".strip()
        return noise_text, "Light"
        
    # 3. 25% HEAVY NOISE (Expressive punctuation & contextual emojis)
    else:
        # Rare elongation: only 20% of heavy noise rows (= 5% overall dataset)
        if random.random() < 0.20:
            text = apply_native_elongation(text, lang)
            
        if "Sarcastic" in subcategory:
            emojis = random.choice(["😂😂", "💀💀", "🤡🤡", "🙄🙄", "🤦‍♂️"])
            punc = random.choice(["... ", "!! ", "??? "])
        elif "Against" in subcategory:
            emojis = random.choice(["🙄", "🤡", "🤦‍♂️", ""])
            punc = random.choice(["... ", "!! ", "??? "])
        elif "Favour" in subcategory:
            emojis = random.choice(["🚨🚨", "🔥🔥", "⚠️⚠️", "🌍💔"])
            punc = random.choice(["!! ", "... ", "! "])
        elif "Spam" in subcategory:
            emojis = random.choice(["🔥🔥💯", "👇👇👇", "💰💰"])
            punc = random.choice(["!! ", ">> ", " "])
        else:
            emojis = random.choice(["🙏🙏", "❤️❤️", "👍👍", ""])
            punc = random.choice(["... ", "!! ", " "])
            
        noise_text = f"{text.rstrip('।!.')} {punc}{emojis}".strip()
        return noise_text, "Heavy"

